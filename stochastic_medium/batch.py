"""Vectorised wavefront stochastic renderer used by the experiment window.

The image is a Monte Carlo estimate of the volume rendering integral with
weighted-candidate (ratio-tracking style) single scattering and analytic
next-event shadow transmittance.  It is *not* fixed-step alpha blending:
every contribution is generated by random delta-tracking candidates.
"""
from __future__ import annotations

import base64
import io
import math
import random
from typing import Any, Dict, Optional, Tuple

import numpy as np
from PIL import Image

from .errors import EventBudgetExceeded, MajorantViolation
from .fields import ray_aabb_interval_batch
from .integrators import (SCATTER_TINT, background_pixel, hg_phase,
                          trace_path)
from .params import PROB_REL_TOL
from .scenes import FRAME, LIGHT, light_towards

_cell_cache: Dict[str, Any] = {}


def grid_majorants(field, res: int, flawed: bool
                   ) -> Tuple[np.ndarray, np.ndarray]:
    key = f"{id(field)}:{res}:{flawed}"
    if key in _cell_cache:
        return _cell_cache[key]
    lo = field.aabb_min
    hi = field.aabb_max
    h = (hi - lo) / res
    maj = np.zeros((res, res, res))
    for i in range(res):
        for j in range(res):
            for k in range(res):
                c0 = lo + np.array([i, j, k]) * h
                c1 = c0 + h
                if flawed:
                    maj[i, j, k] = field._corner_majorant(c0, c1)
                else:
                    maj[i, j, k] = field.box_density_bound(c0, c1)
    out = (maj, h)
    _cell_cache[key] = out
    return out


def audit_grid(field, res: int) -> Tuple[np.ndarray, Dict[str, Any]]:
    declared, h = grid_majorants(field, res, flawed=True)
    certified, _ = grid_majorants(field, res, flawed=False)
    bad = declared + 1e-10 * np.maximum(1.0, certified) < certified
    info = {"n_bad_cells": int(bad.sum()), "res": res}
    if bad.any():
        ii = np.argmax(certified - declared)
        i, j, k = np.unravel_index(ii, certified.shape)
        lo = field.aabb_min
        hh = (field.aabb_max - lo) / res
        center = lo + (np.array([i, j, k]) + 0.5) * hh
        info.update({
            "cell": [int(i), int(j), int(k)],
            "position": [float(x) for x in center],
            "declared": float(declared[i, j, k]),
            "certified": float(certified[i, j, k]),
        })
    return certified, info


def _hg_phase_vec(cos_theta: np.ndarray, g: float) -> np.ndarray:
    gg = max(-0.999, min(0.999, g)) ** 2
    g = max(-0.999, min(0.999, g))
    denom = 1.0 + g * g - 2.0 * g * cos_theta
    return (1.0 - g * g) / (4.0 * math.pi * denom ** 1.5)


def _shadow_transmittance(field, pos: np.ndarray, light_dir: np.ndarray,
                          kappa: float) -> np.ndarray:
    eps = 1e-4
    o = pos + eps * light_dir[None, :]
    n = pos.shape[0]
    d = np.broadcast_to(light_dir, (n, 3))
    t_near, t_far = ray_aabb_interval_batch(o, d, field.aabb_min,
                                            field.aabb_max)
    t_end = np.maximum(t_far, 0.0)
    tau_d = field.optical_depth_batch(o, light_dir, 0.0, t_end)
    tau = kappa * tau_d
    return np.exp(-np.minimum(tau, 700.0))


def render_single(field, cfg, seed_offset: int = 0
                  ) -> Dict[str, np.ndarray]:
    """Render one orthographic view. cfg is RenderConfig-like."""
    rng = np.random.default_rng(cfg.seed + seed_offset)
    W, H = cfg.width, cfg.height
    spp = cfg.spp

    xs = np.linspace(FRAME["x_min"], FRAME["x_max"], W)
    zs = np.linspace(FRAME["z_min"], FRAME["z_max"], H)
    px = np.tile(np.repeat(np.arange(W), 1), H)  # row-major over z? build below
    gx, gz = np.meshgrid(xs, zs)  # shape (H,W)
    x_pix = gx.reshape(-1)
    z_pix = gz.reshape(-1)
    n_pix = W * H

    # pack spp samples per pixel
    x_all = np.repeat(x_pix, spp)
    z_all = np.repeat(z_pix, spp)
    pix_id = np.repeat(np.arange(n_pix), spp)
    jitter_x = (rng.uniform(-0.5, 0.5, size=x_all.shape)
                * (xs[1] - xs[0]) if getattr(cfg, "jitter", True)
                else np.zeros(x_all.shape))
    jitter_z = (rng.uniform(-0.5, 0.5, size=z_all.shape)
                * (zs[1] - zs[0]) if getattr(cfg, "jitter", True)
                else np.zeros(x_all.shape))
    x_all = x_all + jitter_x
    z_all = z_all + jitter_z

    N = x_all.shape[0]
    oy = FRAME["camera_y"]
    o = np.stack([x_all, np.full(N, oy), z_all], axis=1)
    d = np.zeros((N, 3))
    d[:, 1] = 1.0

    kappa = cfg.kappa
    albedo_rgb = cfg.albedo * SCATTER_TINT
    light_dir = light_towards()
    light_color = LIGHT["color"]
    light_I = LIGHT["intensity"]

    # ---- majorant declaration -------------------------------------------
    repairs = []
    use_grid = cfg.partition in ("certified_grid", "flawed_grid")
    clamp_demo = cfg.policy == "clamp_demo"
    if use_grid:
        flawed = cfg.partition == "flawed_grid"
        if flawed and cfg.policy == "strict":
            _, info = audit_grid(field, cfg.grid_res)
            if info["n_bad_cells"] > 0:
                raise MajorantViolation(
                    "批量渲染前审计发现粗糙角点网格主界过低，整帧样本作废并反馈。",
                    position=info.get("position"),
                    density_majorant_declared=info.get("declared"),
                    safe_density_majorant=info.get("certified") * kappa,
                    declared_majorant=(info.get("declared") or 0) * kappa,
                    partition=cfg.partition,
                    extra={"detected_by": "batch_audit", **info})
        majors_d, h = grid_majorants(field, cfg.grid_res,
                                     flawed and cfg.policy != "discard_resample"
                                     and cfg.policy != "repartition")
        if flawed and cfg.policy in ("discard_resample", "repartition"):
            majors_d, h = grid_majorants(field, cfg.grid_res, False)
            repairs.append({"kind": cfg.policy, "scope": "whole_frame",
                            "grid_res": cfg.grid_res})
        res = cfg.grid_res
    else:
        dbar = field.density_majorant()
        if clamp_demo:
            dbar *= 0.55  # deliberately invalid declaration (biased demo)
            repairs.append({"kind": "clamp_demo_BIASED", "scope": "whole_frame",
                            "declared_density_majorant": dbar})
        M_global = kappa * dbar

    # ray starts its stochastic segment at the y entry plane of the AABB
    y_near = float(field.aabb_min[1])
    y_far = float(field.aabb_max[1])
    t_entry = y_near - oy
    L = y_far - oy

    xz_in = ((x_all >= field.aabb_min[0] - 1e-9)
             & (x_all <= field.aabb_max[0] + 1e-9)
             & (z_all >= field.aabb_min[2] - 1e-9)
             & (z_all <= field.aabb_max[2] + 1e-9))
    active = xz_in.copy()
    t = np.full(N, t_entry)
    P = np.ones(N)
    radiance = np.zeros((N, 3))
    cand_count = np.zeros(N, dtype=np.int64)
    n_real = 0
    n_null = 0
    pmax = 0.0
    clamps = 0
    iterations = 0

    bg = np.stack([background_pixel(float(x), float(z))
                   for x, z in zip(x_pix, z_pix)])[pix_id]

    def finish(ids):
        nonlocal radiance, active
        radiance[ids] += P[ids, None] * bg[ids]
        active[ids] = False

    # rays that miss the AABB cross no medium and see pure background
    finish(np.flatnonzero(~xz_in))

    if use_grid:
        entry_pts = o + d * t_entry
        cell = np.floor((entry_pts - field.aabb_min) / h).astype(np.int64)
        cell[:, 1] = 0
        cell[:, 0] = np.clip(cell[:, 0], 0, res - 1)
        cell[:, 2] = np.clip(cell[:, 2], 0, res - 1)

    for _it in range(cfg.max_iterations):
        iterations = _it + 1
        ids = np.flatnonzero(active)
        if ids.size == 0:
            break

        if use_grid:
            ci = cell[ids, 0]
            cj = cell[ids, 1]
            ck = cell[ids, 2]
            M = kappa * majors_d[ci, cj, ck]
            # distance to next y grid plane (camera rays are +y orthographic)
            iy = cj
            plane_hi = field.aabb_min[1] + (iy + 1) * h[1]
            t_boundary = plane_hi - oy  # d_y = 1, o_y = oy, t absolute from 0
        else:
            M = np.full(ids.size, M_global)
            t_boundary = np.full(ids.size, np.inf)

        m_pos = M > 0.0
        step = np.full(ids.size, np.inf)
        uu = rng.random(ids.size)
        step[m_pos] = -np.log(1.0 - uu[m_pos]) / M[m_pos]
        t_cand = t[ids] + step
        t_limit = np.minimum(t_boundary, L)

        cross = t_cand >= t_limit
        # advance crossing rays to cell boundary / end
        cross_ids = ids[cross]
        t[cross_ids] = t_limit[cross]
        at_end = t_limit[cross] >= L - 1e-10
        end_ids = cross_ids[at_end]
        if end_ids.size:
            finish(end_ids)
        boundary_ids = cross_ids[~at_end]
        if boundary_ids.size and use_grid:
            cell[boundary_ids, 1] += 1  # +y orthographic rays
            out_grid = cell[boundary_ids, 1] >= res
            if out_grid.any():
                og = boundary_ids[out_grid]
                finish(og)
                cell[og, 1] = res - 1

        cand_local = ~cross
        cids = ids[cand_local]
        if cids.size == 0:
            continue

        tc = t_cand[cand_local]
        pos = o[cids] + d[cids] * tc[:, None]
        dens = np.asarray(field.density(pos), float)
        sigma = kappa * dens
        M_c = M[cand_local]
        p_raw = sigma / np.maximum(M_c, 1e-300)
        pmax = max(pmax, float(np.max(p_raw)))

        over = p_raw > 1.0 + PROB_REL_TOL
        if over.any() and cfg.policy == "strict":
            w = int(np.argmax(p_raw))
            wid = cids[w]
            raise MajorantViolation(
                "批量随机跟踪发现 sigma_t > M，整帧结果不可信，已停止且未夹紧。",
                position=[float(x) for x in pos[w]],
                ray_t=float(tc[w]),
                declared_majorant=float(M_c[w]),
                actual_sigma_t=float(sigma[w]),
                raw_accept_probability=float(p_raw[w]),
                density=float(dens[w]),
                partition=cfg.partition,
                extra={"detected_by": "candidate_batch",
                       "n_over": int(over.sum())})
        if clamp_demo:
            p = np.clip(p_raw, 0.0, 1.0)
        else:
            p = np.minimum(p_raw, 1.0)
            clamps += int(((p_raw > 1.0) & ~over).sum())

        # next-event shadow lighting at every weighted candidate
        shadow = _shadow_transmittance(field, pos, light_dir, kappa)
        cos_t = d[cids] @ light_dir
        phase = _hg_phase_vec(cos_t, cfg.g)
        local_rgb = (P[cids][:, None] * p[:, None] * albedo_rgb[None, :]
                     * phase[:, None] * shadow[:, None]
                     * light_color[None, :] * light_I)
        radiance[cids] += local_rgb

        # classify real/null purely for event statistics
        au = rng.random(cids.size)
        real = au < p
        n_real += int(real.sum())
        n_null += int((~real).sum())

        P[cids] *= 1.0 - p
        t[cids] = tc
        cand_count[cids] += 1

    if active.any():
        raise EventBudgetExceeded(
            f"批量渲染在 {cfg.max_iterations} 轮后仍有 "
            f"{int(active.sum())} 条光线未结束（介质过浓？）。",
            {"remaining_rays": int(active.sum())})

    # aggregate spp -> pixels
    img = radiance.reshape(H, W, spp, 3).mean(axis=2)
    trans = P.reshape(H, W, spp).mean(axis=2)
    cand_map = cand_count.reshape(H, W, spp).mean(axis=2)

    stats = {
        "iterations": iterations,
        "mean_candidates": float(cand_count.mean()),
        "max_candidates": int(cand_count.max()),
        "real_events": n_real,
        "null_events": n_null,
        "pmax": pmax,
        "tolerance_clamps": clamps,
        "repairs": repairs,
        "n_rays": int(N),
    }
    return {"rgb": img, "trans": trans, "cand": cand_map, "stats": stats}


def render_multi_scalar(field, cfg, seed_offset: int = 0,
                        max_width: int = 80, max_height: int = 50
                        ) -> Dict[str, Any]:
    """Genuine finite-bounce path-traced preview (scalar kernel per ray).

    Multi-bounce delta tracking needs arbitrary-direction grid walks, so for
    the experiment window this path deliberately reuses the tested scalar
    :func:`trace_path` kernel at a capped preview resolution.  One call is one
    sample per preview pixel; the server accumulates calls for convergence.
    """
    scale = min(max_width / cfg.width, max_height / cfg.height, 1.0)
    W = max(24, int(round(cfg.width * scale)))
    H = max(16, int(round(cfg.height * scale)))
    xs = np.linspace(FRAME["x_min"], FRAME["x_max"], W)
    zs = np.linspace(FRAME["z_min"], FRAME["z_max"], H)
    oy = FRAME["camera_y"]
    L = float(field.aabb_max[1]) - oy
    light_dir = light_towards()

    rgb = np.zeros((H, W, 3))
    through = np.zeros((H, W))
    cand = np.zeros((H, W))
    n_rays = 0
    n_cand_total = 0
    pmax = 0.0

    for iz, z in enumerate(zs):
        for ix, x in enumerate(xs):
            seed = (int(cfg.seed) + seed_offset * 7919
                    + (iz * W + ix) * 104729) & 0x7FFFFFFF
            rng = random.Random(seed)
            out = trace_path(
                field, np.array([float(x), oy, float(z)]),
                np.array([0.0, 1.0, 0.0]), L,
                kappa=cfg.kappa, albedo=cfg.albedo, g=cfg.g,
                light_dir=light_dir, light_color=LIGHT["color"],
                light_intensity=LIGHT["intensity"],
                max_bounces=cfg.max_bounces,
                partition=cfg.partition, grid_res=cfg.grid_res,
                policy=cfg.policy, rng=rng,
                record_candidates=False)
            rgb[iz, ix] = out["radiance"]
            tf = out.get("throughput_final", [1.0, 1.0, 1.0])
            through[iz, ix] = float(np.mean(tf))
            nc = sum(int(b.get("n_candidates", 0)) for b in out["bounces"])
            cand[iz, ix] = nc
            n_rays += 1
            n_cand_total += nc

    stats = {
        "iterations": cfg.max_bounces + 1,
        "mean_candidates": n_cand_total / max(1, n_rays),
        "max_candidates": int(cand.max()),
        "real_events": None,
        "null_events": None,
        "pmax": pmax,
        "tolerance_clamps": 0,
        "repairs": [],
        "n_rays": n_rays,
        "preview_width": W,
        "preview_height": H,
        "scalar_multi_bounce": True,
    }
    return {"rgb": rgb, "trans": through, "cand": cand, "stats": stats}


def tonemap_png_base64(rgb: np.ndarray, exposure: float) -> str:
    x = np.maximum(rgb * exposure, 0.0)
    x = (x * (2.51 * x + 0.03)) / (x * (2.43 * x + 0.59) + 0.14)
    x = np.clip(x, 0.0, 1.0)
    srgb = np.where(x <= 0.0031308, 12.92 * x,
                    1.055 * np.power(x, 1 / 2.4) - 0.055)
    arr = (np.clip(srgb, 0, 1) * 255).astype(np.uint8)
    im = Image.fromarray(arr, "RGB")
    buf = io.BytesIO()
    im.save(buf, format="PNG")
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()


def heatmap_png_base64(values: np.ndarray, vmin: float, vmax: float) -> str:
    v = np.clip((values - vmin) / max(vmax - vmin, 1e-9), 0, 1)
    # simple navy -> cyan -> yellow false colour
    r = np.clip(1.5 * v - 0.5, 0, 1)
    g = np.clip(1.5 * v - 0.0, 0, 1)
    b = np.clip(1.2 - 1.5 * v, 0, 1)
    arr = (np.stack([r, g, b], axis=-1) * 255).astype(np.uint8)
    im = Image.fromarray(arr, "RGB")
    buf = io.BytesIO()
    im.save(buf, format="PNG")
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
